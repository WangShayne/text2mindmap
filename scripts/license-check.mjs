// Checks dependency licenses and (with --write-notices) regenerates THIRD_PARTY_NOTICES.md.
// Fails on copyleft / source-available / non-commercial licenses. A dual license such as
// jszip's "(MIT OR GPL-3.0-or-later)" passes because one permissive option can be chosen.
import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const DENY = /\b(A?GPL|LGPL|SSPL|BUSL|BSL|CC-BY-NC|CC-BY-NC-SA|CC-BY-NC-ND|Commons[- ]Clause|EUPL|OSL|RPL)\b/i
const root = process.cwd()

// Packages that ship without a license file: use the upstream text.
const MIT = (holder) => `The MIT License (MIT)\n\nCopyright (c) ${holder}\n\nPermission is hereby granted, free of charge, to any person obtaining a copy\nof this software and associated documentation files (the "Software"), to deal\nin the Software without restriction, including without limitation the rights\nto use, copy, modify, merge, publish, distribute, sublicense, and/or sell\ncopies of the Software, and to permit persons to whom the Software is\nfurnished to do so, subject to the following conditions:\n\nThe above copyright notice and this permission notice shall be included in all\ncopies or substantial portions of the Software.\n\nTHE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR\nIMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,\nFITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE\nAUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER\nLIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,\nOUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE\nSOFTWARE.`
const OVERRIDES = { 'simple-mind-map': MIT('2021-2023 The MindMap Team (https://github.com/wanglin2/mind-map)') }

function tree(omitDev) {
  const out = execSync(`npm ls --all --json --long ${omitDev ? '--omit=dev' : ''}`, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] })
  const seen = new Map()
  const walk = (deps) => {
    for (const [name, info] of Object.entries(deps ?? {})) {
      if (!info.version) continue
      const key = `${name}@${info.version}`
      if (!seen.has(key)) seen.set(key, { name, version: info.version, dir: info.path })
      walk(info.dependencies)
    }
  }
  walk(JSON.parse(out).dependencies)
  return [...seen.values()]
}

function info(name, version, dirHint) {
  for (const dir of [dirHint, path.join(root, 'node_modules', name)].filter(Boolean)) {
    if (!fs.existsSync(path.join(dir, 'package.json'))) continue
    const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
    if (pj.version !== version) continue
    let license = pj.license ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type ?? l).join(' OR ') : undefined)
    if (typeof license === 'object' && license) license = license.type
    const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f))
    const text = file ? fs.readFileSync(path.join(dir, file), 'utf8') : ''
    const notice = fs.readdirSync(dir).find((f) => /^notice(\.|$)/i.test(f))
    return { license: String(license ?? 'UNKNOWN'), text, notice: notice && notice !== file ? fs.readFileSync(path.join(dir, notice), 'utf8') : '', repo: typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? pj.homepage ?? '' }
  }
  return { license: 'UNKNOWN', text: '', notice: '', repo: '' }
}

function allowed(expr) {
  const alts = expr.replace(/[()]/g, '').split(/\s+OR\s+/i)
  return alts.some((alt) => alt.split(/\s+AND\s+/i).every((l) => !DENY.test(l) && l.trim() !== 'UNKNOWN' && l.trim() !== 'UNLICENSED'))
}

const all = tree(false)
const prod = new Set(tree(true).map((p) => `${p.name}@${p.version}`))
const bad = []
const counts = {}
const rows = []
for (const p of all) {
  const i = info(p.name, p.version, p.dir)
  counts[i.license] = (counts[i.license] ?? 0) + 1
  if (!allowed(i.license)) bad.push(`${p.name}@${p.version}: ${i.license}${prod.has(`${p.name}@${p.version}`) ? ' (shipped)' : ' (dev only)'}`)
  if (!i.text && OVERRIDES[p.name]) i.text = OVERRIDES[p.name]
  if (prod.has(`${p.name}@${p.version}`)) rows.push({ ...p, ...i })
}

console.log(`Checked ${all.length} packages (${prod.size} shipped).`)
console.log(Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `  ${k}: ${v}`).join('\n'))

if (process.argv.includes('--write-notices')) {
  rows.sort((a, b) => a.name.localeCompare(b.name))
  let md = `# Third-party notices\n\ntext2mindmap bundles the following open-source packages in its frontend and server builds (generated by \`npm run notices\`).\n\n`
  md += `The mind map is built on SimpleMindMap (simple-mind-map, MIT, https://github.com/wanglin2/mind-map).\n本产品思维导图基于SimpleMindMap项目开发，版权归源项目所有。\n\n`
  md += `Speech recognition: text2mindmap recommends, but does not bundle, the SenseVoice model (SenseVoice-Small, https://github.com/QwenAudio/SenseVoice, code under the MIT license; see that repository for the model license), served by FunASR sensevoice-server (https://www.funasr.com/en/deploy/sensevoice-native-server.html). Users download and run it themselves.\n语音识别推荐自托管 SenseVoice 模型（未随本产品分发），版权归源项目所有。\n\n`
  md += `jszip is dual-licensed "(MIT OR GPL-3.0-or-later)"; text2mindmap uses it under the MIT license.\n\n`
  md += `| Package | Version | License |\n|---|---|---|\n` + rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n') + '\n\n---\n\n'
  const byText = new Map()
  for (const r of rows) {
    const key = (r.text || `(No license file in the package. License: ${r.license})`).trim()
    if (!byText.has(key)) byText.set(key, [])
    byText.get(key).push(r)
  }
  for (const [text, list] of byText) {
    md += `## ${list.map((r) => `${r.name}@${r.version}`).join(', ')}\n\n\`\`\`\n${text}\n\`\`\`\n\n`
    for (const r of list) if (r.notice) md += `NOTICE for ${r.name}:\n\n\`\`\`\n${r.notice.trim()}\n\`\`\`\n\n`
  }
  fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), md)
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages).`)
}

if (bad.length) {
  console.error(`\nDisallowed or unknown licenses:\n  ${bad.join('\n  ')}`)
  process.exit(1)
}
console.log('License check passed.')
