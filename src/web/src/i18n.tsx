export type Lang = 'en' | 'zh'
export type TKey = keyof Dict
const dicts: Record<Lang, Dict> = { en, zh }

function initialLang(): Lang {
  const saved = localStorage.getItem('t2m.lang')
  if (saved === 'en' || saved === 'zh') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string | number>) => string }>(null!)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => { localStorage.setItem('t2m.lang', l); document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'; setLangState(l) }
  const t = (k: TKey, vars?: Record<string, string | number>) => {
    let s = dicts[lang][k] ?? en[k]
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.split(`{${vk}}`).join(String(vv))
    return s
  }
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
